/**
 * Regenerates supabase/seed.sql from the TypeScript seed data in src/lib/data/seed.ts
 * so the demo dataset and the database seed never drift apart.
 *
 *   node scripts/gen-seed-sql.mjs
 */
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// The seed file is plain data, so stripping the handful of type annotations it uses
// is enough to import it directly in Node without a TypeScript toolchain.
// The seed file is plain data, so stripping the handful of type annotations it uses
// is enough to import it directly in Node without a TypeScript toolchain.
const source = readFileSync("src/lib/data/seed.ts", "utf8")
  .replace(/^import type .*$/gm, "")
  .replace(/^type\s+\w+\s*=[\s\S]*?\n[\]}];\n/gm, "")
  .replace(/^(export )?const (\w+): [^=\n]+=/gm, "$1const $2 =")
  .replace(/\(daysAgo: number\)/, "(daysAgo)");

const dir = mkdtempSync(join(tmpdir(), "cohort-seed-"));
const file = join(dir, "seed.mjs");
writeFileSync(file, source);

const { SEED_PEOPLE, SEED_RESOURCES, SEED_OPPORTUNITIES, SEED_HELP_REQUESTS } = await import(
  `file://${file}`
);

const q = (value) => (value === null || value === undefined ? "NULL" : `'${String(value).replace(/'/g, "''")}'`);
const arr = (values) => `ARRAY[${values.map(q).join(", ")}]::text[]`;
const ref = (id) => (id ? `(select id from public.users where email = ${q(byId(id).email)})` : "NULL");

const peopleById = new Map(SEED_PEOPLE.map((p) => [p.id, p]));
function byId(id) {
  const person = peopleById.get(id);
  if (!person) throw new Error(`Unknown seed person: ${id}`);
  return person;
}

const lines = [
  "-- Coup — seed data (generated by scripts/gen-seed-sql.mjs; do not edit by hand)",
  "-- Run after schema.sql. Safe to re-run: it clears the demo rows first.",
  "",
  "delete from public.help_requests;",
  "delete from public.opportunities;",
  "delete from public.resources;",
  "delete from public.users;",
  "",
  "insert into public.users (name, email, bio, \"current_role\", cohort_group, location, linkedin_url, contact_preference, contact_handle, role) values",
];

lines.push(
  SEED_PEOPLE.map((p) =>
    `  (${[q(p.name), q(p.email), q(p.bio), q(p.currentRole), q(p.group), q(p.location), q(p.linkedinUrl), q(p.contactPreference), q(p.contactHandle), q(p.role)].join(", ")})`,
  ).join(",\n") + ";",
  "",
);

const childInserts = [
  ["experience", (p) => p.experience.map((e) => `  (${ref(p.id)}, ${q(e.company)}, ${q(e.industry)}, ${q(e.function)}, ${e.years})`), "user_id, company, industry, function, years"],
  ["skills", (p) => p.skills.map((s) => `  (${ref(p.id)}, ${q(s)})`), "user_id, skill"],
  ["interests", (p) => p.interests.map((s) => `  (${ref(p.id)}, ${q(s)})`), "user_id, interest"],
  ["looking_for", (p) => p.lookingFor.map((s) => `  (${ref(p.id)}, ${q(s)})`), "user_id, category"],
];

for (const [table, rowsFor, columns] of childInserts) {
  const rows = SEED_PEOPLE.flatMap(rowsFor);
  if (!rows.length) continue;
  lines.push(`insert into public.${table} (${columns}) values`, rows.join(",\n") + ";", "");
}

lines.push(
  "insert into public.resources (title, description, category, url, tags, uploaded_by, created_at) values",
  SEED_RESOURCES.map(
    (r) =>
      `  (${[q(r.title), q(r.description), q(r.category), q(r.url), arr(r.tags), ref(r.uploadedBy), q(r.createdAt)].join(", ")})`,
  ).join(",\n") + ";",
  "",
  "insert into public.opportunities (title, company, type, industry, role, location, deadline, description, url, posted_by, status, created_at) values",
  SEED_OPPORTUNITIES.map(
    (o) =>
      `  (${[q(o.title), q(o.company), q(o.type), q(o.industry), q(o.role), q(o.location), q(o.deadline), q(o.description), q(o.url), ref(o.postedBy), q(o.status), q(o.createdAt)].join(", ")})`,
  ).join(",\n") + ";",
  "",
  "insert into public.help_requests (title, description, tags, posted_by, status, created_at) values",
  SEED_HELP_REQUESTS.map(
    (h) =>
      `  (${[q(h.title), q(h.description), arr(h.tags), ref(h.postedBy), q(h.status), q(h.createdAt)].join(", ")})`,
  ).join(",\n") + ";",
  "",
);

writeFileSync("supabase/seed.sql", lines.join("\n"));
console.log("Wrote supabase/seed.sql");
